// Deploy the full Sentinel system across Sepolia (origin + destination) and
// Lasna (reactive contract), then wire it together and fund both sides.
// Prerequisites (checked up front, with instructions if missing):
//   - Sepolia ETH in the deployer wallet (deployments + vault funding + gas)
//   - lREACT on Lasna in the same wallet (sentinel deployment + funding)
//     -> get it with: node scripts/fund-lasna.mjs
// Usage: node scripts/deploy-all.mjs
// Writes deployments.json and web/config.js (used by the UI).
import fs from "node:fs";
import path from "node:path";
import { ethers } from "ethers";
import { CHAINS, ROOT, artifact, deploy, loadDeployer, readDeployments, writeDeployments, fmtUSD } from "./common.mjs";

const sepolia = new ethers.JsonRpcProvider(CHAINS.sepolia.rpc);
const lasna = new ethers.JsonRpcProvider(CHAINS.lasna.rpc);
const sepWallet = loadDeployer(sepolia);
const lasnaWallet = loadDeployer(lasna);
const addr = await sepWallet.getAddress();

console.log(`== Sentinel deploy-all ==\ndeployer ${addr}`);
console.log(`Sepolia RPC: ${CHAINS.sepolia.rpc}\nLasna RPC:   ${CHAINS.lasna.rpc}`);

const sepBal = await sepolia.getBalance(addr);
const lBal = await lasna.getBalance(addr);
console.log(`balances: ${ethers.formatEther(sepBal)} Sepolia ETH, ${ethers.formatEther(lBal)} lREACT`);
if (sepBal < ethers.parseEther("0.02")) {
  throw new Error(
    `not enough Sepolia ETH (${ethers.formatEther(sepBal)}). Get some from a faucet ` +
      `(e.g. https://sepolia-faucet.pk910.de — PoW, no account) and retry.`
  );
}
if (lBal < ethers.parseEther("0.5")) {
  throw new Error(
    `not enough lREACT on Lasna (${ethers.formatEther(lBal)}). Run: node scripts/fund-lasna.mjs`
  );
}

const prev = readDeployments();
const out = { ...prev, deployer: addr, chainIds: { sepolia: "11155111", lasna: "5318007" } };

// 1. Origin-chain contracts on Sepolia.
console.log("\n-- Sepolia: price feed + token --");
const feed = prev.feed
  ? new ethers.Contract(prev.feed, artifact("MockPriceFeed").abi, sepWallet)
  : await deploy("MockPriceFeed", sepWallet, [2000_00000000n]);
out.feed = await feed.getAddress();
console.log(`MockPriceFeed ${out.feed} (price ${fmtUSD(await feed.getPrice())})`);

const token = prev.token
  ? new ethers.Contract(prev.token, artifact("MockToken").abi, sepWallet)
  : await deploy("MockToken", sepWallet);
out.token = await token.getAddress();
console.log(`MockToken ${out.token}`);
const mintTx = await token.mint(addr, ethers.parseEther("1000"));
await mintTx.wait();
console.log(`minted 1000 sUSD to deployer (tx ${mintTx.hash})`);

// 2. Reactive contract on Lasna (subscribes to the feed in its constructor).
console.log("\n-- Lasna: sentinel --");
// Lasna rejects type-2 txs with a 0 priority fee ("gas tip cap 0, minimum
// needed 1") — ethers defaults it to 0 from the RPC's fee data, so set it
// explicitly (1 gwei tip, 200 gwei max fee matches the chain's fee market).
const lasnaFees = {
  maxPriorityFeePerGas: 1_000_000_000n,
  maxFeePerGas: 200_000_000_000n,
};
const sentinel = prev.sentinel
  ? new ethers.Contract(prev.sentinel, artifact("StopLossSentinel").abi, lasnaWallet)
  : await deploy("StopLossSentinel", lasnaWallet, [out.feed, CHAINS.sepolia.chainId], ethers.parseEther("1"), lasnaFees);
out.sentinel = await sentinel.getAddress();
console.log(`StopLossSentinel ${out.sentinel}`);
console.log(`  Lasna explorer: ${CHAINS.lasna.explorer}/address/${out.sentinel}`);

// 3. Vault on Sepolia, authorized for this sentinel, funded for callback gas.
console.log("\n-- Sepolia: vault --");
const vault = prev.vault
  ? new ethers.Contract(prev.vault, artifact("StopLossVault").abi, sepWallet)
  : await deploy(
      "StopLossVault",
      sepWallet,
      [CHAINS.sepolia.callbackProxy, out.sentinel, out.token],
      // 0.01 ETH covers callback gas (coverDebt) for the demo at Sepolia prices;
      // lowered from 0.05 because the deployer only holds 0.05 ETH total.
      ethers.parseEther("0.01")
    );
out.vault = await vault.getAddress();
console.log(`StopLossVault ${out.vault}`);
console.log(`  Sepolia explorer: ${CHAINS.sepolia.explorer}/address/${out.vault}`);

// 4. Point the sentinel at the vault.
console.log("\n-- wiring: sentinel.setVault --");
if ((await sentinel.vault()) !== out.vault) {
  const tx = await sentinel.setVault(out.vault, lasnaFees);
  await tx.wait();
  console.log(`setVault tx ${tx.hash}`);
} else {
  console.log("vault already set");
}

writeDeployments(out);
fs.writeFileSync(
  path.join(ROOT, "web", "config.js"),
  `// Generated by scripts/deploy-all.mjs — do not edit by hand.\nwindow.SENTINEL_CONFIG = ${JSON.stringify(
    {
      sepoliaRpc: CHAINS.sepolia.rpc,
      lasnaRpc: CHAINS.lasna.rpc,
      feed: out.feed,
      token: out.token,
      vault: out.vault,
      sentinel: out.sentinel,
      deployer: addr,
    },
    null,
    2
  )};\n`
);
console.log("\n== deployed ==\n" + JSON.stringify(out, null, 2));
console.log("\nNext: node scripts/demo-flow.mjs  (runs the full loop and measures latency)");
